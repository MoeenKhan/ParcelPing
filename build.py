"""Build a single-file Windows .exe into dist/ (or the folder given).

    venv\\Scripts\\python build.py [output_dir]
"""

from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))

from app import __version__, config  # noqa: E402


def make_icon() -> Path:
    from PySide6.QtGui import QGuiApplication

    from app.ui.icon import render

    app = QGuiApplication.instance() or QGuiApplication(["build", "-platform", "offscreen"])  # noqa: F841
    assets = ROOT / "assets"
    assets.mkdir(exist_ok=True)
    ico = assets / "icon.ico"
    # Qt's ICO writer stores one size per file; 256px scales down well in Explorer.
    if not render(256).save(str(ico), "ICO"):
        raise SystemExit("could not write icon.ico")
    return ico


# Python modules PyInstaller would otherwise pull in.
EXCLUDE_MODULES = [
    "tkinter",
    "PySide6.QtQml", "PySide6.QtQuick", "PySide6.QtSql", "PySide6.QtTest",
    "PySide6.QtOpenGL", "PySide6.QtPdf",
]

# Bundled files the app never loads (patterns match the path inside the
# bundle, lower-case). The one-file .exe unpacks everything to %TEMP% on each
# launch, so each MB here also costs start-up time.
DROP_FILES = [
    "pyside6/opengl32sw.dll",              # software OpenGL; the UI is plain widgets
    "pyside6/translations/*",              # Qt's own dialog translations; UI is English
    "pyside6/plugins/imageformats/*",      # no image files are loaded; icons are drawn
    "pyside6/plugins/iconengines/*",       # SVG icons
    "pyside6/qt6svg.dll",
    "pyside6/plugins/tls/*",               # HTTPS goes through Python, not Qt
    "pyside6/plugins/networkinformation/*",
    "libssl-3-x64.dll",                    # Qt's OpenSSL (Python uses libssl-3.dll)
    "libcrypto-3-x64.dll",
    "pyside6/plugins/generic/*",           # touch input
    "pyside6/plugins/styles/*",            # Fusion is built in
    "pyside6/plugins/platforms/qdirect2d.dll",
    "pyside6/plugins/platforms/qminimal.dll",
    "pyside6/plugins/platforms/qoffscreen.dll",
]

SPEC = """\
# Generated by build.py on each build; edit build.py instead.
from fnmatch import fnmatch

DROP = {drop!r}


def keep(entry):
    dest = entry[0].replace("\\\\", "/").lower()
    return not any(fnmatch(dest, pattern) for pattern in DROP)


a = Analysis([{main!r}], pathex=[{root!r}], excludes={excludes!r}, noarchive=False, optimize=0)
dropped = [e for e in a.binaries + a.datas if not keep(e)]
a.binaries = [e for e in a.binaries if keep(e)]
a.datas = [e for e in a.datas if keep(e)]
print(f"build.py: left out {{len(dropped)}} unused files")
pyz = PYZ(a.pure)
exe = EXE(
    pyz, a.scripts, a.binaries, a.datas, [],
    name={name!r},
    icon=[{icon!r}],
    console=False,
    debug=False,
    strip=False,
    upx=False,
    runtime_tmpdir=None,
)
"""


def write_spec(ico: Path) -> Path:
    spec = ROOT / "build" / f"{config.APP_NAME}.spec"
    spec.parent.mkdir(exist_ok=True)
    spec.write_text(SPEC.format(
        drop=DROP_FILES,
        main=str(ROOT / "main.py"),
        root=str(ROOT),
        excludes=EXCLUDE_MODULES,
        name=config.APP_NAME,
        icon=str(ico),
    ), encoding="utf-8")
    return spec


def main() -> None:
    dist = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else ROOT / "dist"
    for d in (ROOT / "build", dist):
        shutil.rmtree(d, ignore_errors=True)
    ico = make_icon()
    spec = write_spec(ico)
    subprocess.run(
        [sys.executable, "-m", "PyInstaller", str(spec), "--noconfirm",
         "--workpath", str(ROOT / "build"), "--distpath", str(dist)],
        cwd=ROOT,
        check=True,
    )
    exe = dist / f"{config.APP_NAME}.exe"
    print(f"\nBuilt {exe}  ({exe.stat().st_size / 1e6:.1f} MB), version {__version__}")


if __name__ == "__main__":
    main()
